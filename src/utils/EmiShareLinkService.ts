import store from '@/store/store';
import { supabase } from '@/supabase/supabase';
import type { NumberFormatMode } from '@/types/account.types';
import { IEmiShareLink, IPublicEmi, PublicEmiData, ScheduleData } from '@/types/emi.types';

const NUMBER_FORMATS: readonly NumberFormatMode[] = ['exact', 'compact_short', 'compact_long'];

const resolveUserId = async (): Promise<string> => {
    const { id } = store.getState().userModel;
    if (id) {
        return id;
    }

    const { data: user } = await supabase.auth.getUser();
    return user.user?.id || '';
};

const requireUserId = async (): Promise<string> => {
    const userId = await resolveUserId();
    if (!userId) {
        throw new Error('You must be signed in to manage share links.');
    }
    return userId;
};

const mapLinkRow = (row: Record<string, unknown>): IEmiShareLink => ({
    id: String(row.id),
    emiId: String(row.emiId),
    token: String(row.token),
    createdAt: String(row.createdAt ?? ''),
});

const toOptionalNumber = (value: unknown): number | undefined =>
    value === null || value === undefined ? undefined : Number(value);

const mapPublicScheduleRow = (row: Record<string, unknown>): ScheduleData => ({
    month: Number(row.month),
    billDate: String(row.billDate),
    emi: String(Number(row.emi)),
    interest: String(Number(row.interest)),
    principalPaid: String(Number(row.principalPaid)),
    balance: String(Number(row.balance)),
    gst: Number(row.gst ?? 0),
});

const mapPublicEmiRow = (row: Record<string, unknown>, schedule: unknown[]): PublicEmiData => ({
    id: String(row.id),
    itemName: String(row.itemName ?? ''),
    currency: String(row.currency),
    principal: Number(row.principal),
    interestRate: Number(row.interestRate),
    interestDiscount: Number(row.interestDiscount ?? 0),
    interestDiscountType: row.interestDiscountType === 'amount' ? 'amount' : 'percent',
    tenure: Number(row.tenure),
    billDate: new Date(String(row.billDate)),
    endDate: new Date(String(row.endDate)),
    emi: Number(row.emi),
    totalLoan: Number(row.totalLoan),
    totalInterest: Number(row.totalInterest),
    gst: Number(row.gst ?? 0),
    totalGST: Number(row.totalGST ?? 0),
    processingFee: toOptionalNumber(row.processingFee),
    processingFeeGst: toOptionalNumber(row.processingFeeGst),
    totalPaidEMIs: Number(row.totalPaidEMIs ?? 0),
    remainingBalance: Number(row.remainingBalance),
    remainingTenure: Number(row.remainingTenure),
    isCompleted: Boolean(row.isCompleted),
    tag: row.tag ? String(row.tag) : undefined,
    amortizationSchedules: schedule.map((item) => mapPublicScheduleRow(item as Record<string, unknown>)),
});

const mapPublicPayload = (payload: Record<string, unknown>): IPublicEmi => {
    const format = (payload.format ?? {}) as Record<string, unknown>;
    const numberFormat = NUMBER_FORMATS.find((mode) => mode === format.numberFormat) ?? 'exact';

    return {
        emi: mapPublicEmiRow(
            payload.emi as Record<string, unknown>,
            Array.isArray(payload.schedule) ? payload.schedule : []
        ),
        format: {
            locale: String(format.locale || 'en-IN'),
            numberFormat,
        },
    };
};

export class EmiShareLinkService {
    /** The EMI's live link, or null. Owner-only under RLS. */
    static async getActiveLink(emiId: string): Promise<IEmiShareLink | null> {
        const { data, error } = await supabase
            .from('emiShareLinks')
            .select('id, emiId, token, createdAt')
            .eq('emiId', emiId)
            .is('revokedAt', null)
            .maybeSingle();

        if (error) throw error;
        return data ? mapLinkRow(data) : null;
    }

    /** Creates the EMI's live link. The token is generated by the database. */
    static async createLink(emiId: string): Promise<IEmiShareLink> {
        const userId = await requireUserId();
        const { data, error } = await supabase
            .from('emiShareLinks')
            .insert({ emiId, createdBy: userId })
            .select('id, emiId, token, createdAt')
            .single();

        if (error) throw error;
        return mapLinkRow(data);
    }

    /** Revokes a link; its URL stops working immediately. */
    static async revokeLink(linkId: string): Promise<void> {
        await requireUserId();
        const { error } = await supabase
            .from('emiShareLinks')
            .update({ revokedAt: new Date().toISOString() })
            .eq('id', linkId);

        if (error) throw error;
    }

    /** Anonymous read through get_public_emi(). Null when the link is unknown or revoked. */
    static async fetchPublicEmi(token: string): Promise<IPublicEmi | null> {
        const { data, error } = await supabase.rpc('get_public_emi', { p_token: token });

        if (error) throw error;
        if (!data || typeof data !== 'object' || Array.isArray(data)) return null;
        return mapPublicPayload(data as Record<string, unknown>);
    }
}
